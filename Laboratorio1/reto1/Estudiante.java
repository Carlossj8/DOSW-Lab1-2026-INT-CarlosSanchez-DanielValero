public class Estudiante {
    private String nombre;
    private int edad;
    private int Semestre;
    private String correo;

    public Estudiante(String nombre, int edad, int Semestre, String correo) {
        this.nombre = nombre;
        this.edad = edad;
        this.Semestre = Semestre;
        this.correo = correo;

    }

}